"""Emit a reviewable VBA macro from build_plan.json (no SolidWorks needed).

Mirrors the verified calls from pipeline/solidworks_builder.py and honours the
error ledger (docs/solidworks-macro-error-log.md):
  * E004 — bounding box via IBody2.GetBodyBox, never the invented model-level API.
  * E006 — sketches are consumed as the ACTIVE sketch, never re-selected by name.
Inch->meter conversion is the one from pipeline.coordinate_normalize.to_meters.
"""
from __future__ import annotations

from typing import Any, Dict, List

from pipeline.coordinate_normalize import to_meters  # imported, not copied


_HEADER = """' Auto-generated by dwg_native (DWG-native pipeline). Reviewable artifact.
' Coordinates are the DWG-exact geometry; every value traces to raw_extraction.json.
Option Explicit

Sub main()
    Dim swApp As Object, swModel As Object, swSM As Object, swFM As Object
    Dim swFeat As Object, swBody As Object
    Set swApp = Application.SldWorks
    Set swModel = swApp.NewDocument(swApp.GetUserPreferenceStringValue(8), 0, 0, 0)
    Set swSM = swModel.SketchManager
    Set swFM = swModel.FeatureManager
"""

_FOOTER = """    swModel.ViewZoomtofit2
    swModel.SaveAs3 "%(sldprt)s", 0, 0
    Debug.Print "dwg_native build complete"
End Sub
"""


def emit_vba(build_plan: Dict[str, Any], sldprt_path: str = "part.sldprt") -> str:
    lines: List[str] = [_HEADER]
    factor = build_plan.get("unit_factor_to_meters", 0.0254)

    def m(v):
        return round(float(v) * factor, 9)

    base_done = False
    for step in build_plan.get("steps", []):
        stype = step.get("type")
        fid = step.get("feature_id", "-")
        d = step.get("dimensions_drawing_units", {}) or {}
        pos = (step.get("positions_xy") or [[0.0, 0.0]])[0]

        if stype == "extrude_boss":
            length, width, thick = m(d.get("length", 0)), m(d.get("width", 0)), m(d.get("thickness", 0))
            lines.append(f"""    ' --- {fid}: base plate (profile loop, DWG-exact) ---
    swModel.Extension.SelectByID2 "Front Plane", "PLANE", 0,0,0, False, 0, Nothing, 0
    swSM.InsertSketch True
    swSM.CreateCornerRectangle 0#, 0#, 0#, {length}, {width}, 0#
    swSM.InsertSketch True   ' consume ACTIVE sketch (E006: never re-select by name)
    Set swFeat = swFM.FeatureExtrusion3(True, False, False, 0, 0, {thick}, 0.01, _
        False, False, False, False, 0, 0, False, False, False, False, _
        True, True, True, 0, 0, False)
    If swFeat Is Nothing Then Err.Raise vbObjectError, , "FeatureExtrusion3 None for {fid}"
    swFeat.Name = "{fid}_base"
""")
            base_done = True
        elif stype == "hole":
            if not base_done:
                lines.append(f"    ' WARNING: hole {fid} before base solid — skipped in macro\n")
                continue
            dia = d.get("diameter", 0)
            r = m(dia / 2.0 if dia else 0)
            cx, cy = m(pos[0]), m(pos[1])
            # A blind depth callout cuts to that depth, not through-all (E006-
            # adjacent fix: parity with the COM builder — a counterbore relief /
            # ".16 DP" drill must never be cut clear through the part).
            is_blind = step.get("depth_type") in ("blind", "blind_unknown_depth")
            depth_m = m(d["depth"]) if (is_blind and d.get("depth")) else None
            end_cond = 0 if depth_m else 1
            depth_lit = f"{depth_m}" if depth_m else "0.01"
            # Sketch on "Front Plane" at z=0 — the SAME plane the COM builder
            # uses (dwg_native/build/builder.py), not a FACE selected by an
            # (x,y,z) coordinate hit. 2026-07-28 fix: the two build paths used
            # to sketch holes on DIFFERENT references (this file selected a
            # face at z=thickness; the COM path sketches on Front Plane at
            # z=0), so a user running this VBA macro could get different
            # geometry than the automated COM build — plus SelectByID2 by
            # coordinate hit is exactly the fragile selection pattern
            # documented as failure-prone (a face pick can silently grab the
            # wrong face, or fail entirely, depending on view/occlusion). The
            # COM path is live-verified (STL volume matched analytically
            # expected geometry); VBA now matches it exactly.
            lines.append(f"""    ' --- {fid}: hole diameter {dia} at ({pos[0]}, {pos[1]}) (DWG-exact circle){' - BLIND ' + str(d.get('depth')) if depth_m else ''} ---
    swModel.Extension.SelectByID2 "Front Plane", "PLANE", 0, 0, 0, False, 0, Nothing, 0
    swSM.InsertSketch True
    swSM.CreateCircleByRadius {cx}, {cy}, 0#, {r}
    swSM.InsertSketch True   ' consume ACTIVE sketch (E006)
    Set swFeat = swFM.FeatureCut4(True, False, False, {end_cond}, 0, {depth_lit}, 0.01, _
        False, False, False, False, 0, 0, False, False, False, False, False, _
        True, True, True, True, False, 0, 0, False)
    If swFeat Is Nothing Then Err.Raise vbObjectError, , "FeatureCut4 None for {fid}"
    swFeat.Name = "{fid}_hole"
""")
        # setup/verify/export handled by header/footer

    # E004: read bbox from the body, never the invented model-level bbox API.
    lines.append("""    ' --- bbox sanity via IBody2.GetBodyBox (E004: use the body box) ---
    Dim vBodies As Variant
    vBodies = swModel.GetBodies2(0, False)
    If Not IsEmpty(vBodies) Then
        Set swBody = vBodies(0)
        Dim box As Variant
        box = swBody.GetBodyBox
        Debug.Print "bbox: "; box(0); box(1); box(2); box(3); box(4); box(5)
    End If
""")
    lines.append(_FOOTER % {"sldprt": sldprt_path.replace("\\", "\\\\")})
    return "".join(lines)
